function run_mpassit_mean {
    # $1        $2
    # wrkdir    iseconds
    local dawrkdir=$1
    local iseconds=$2

    #
    # Build working directory
    #
    local wrkdir=${dawrkdir}/mpassit_mean
    mkwrkdir $wrkdir 0
    cd $wrkdir || return

    #
    # Waiting for job conditions
    #
    local -a conditions
    conditions=("$(realpath -m --relative-to=. ${dawrkdir}/jedi_solver/done.solver)")

    if [[ $dorun == true ]]; then
        for cond in "${conditions[@]}"; do
            mecho0 "Checking $cond...."
            while [[ ! -e $cond ]]; do
                if [[ $verb -eq 1 ]]; then
                    mecho0 "Waiting for file: $cond"
                fi
                sleep 10
            done
        done
    fi

    #
    # Prepare MPASSIT working files
    #
    if [[ "${mpscheme}" == "mp_nssl2m" ]]; then
        fileappend="NSSL"
    else
        fileappend="THOM"
    fi

    rm -f core.*           # Maybe core-dumped, resubmission will solves the problem if the machine is unstable.

    # Linking working file for this member
    parmfiles=(diaglist histlist_2d histlist_3d )
    for fn in "${parmfiles[@]}"; do
        if [[ ! -e $fn ]]; then
            #if [[ $verb -eq 1 ]]; then echo "Linking $fn ..."; fi
            if [[ -e $FIXDIR/MPASSIT/${fn}.${fileappend}_analysis_mean ]]; then
                ln -sf $FIXDIR/MPASSIT/${fn}.${fileappend}_analysis_mean $fn
            elif [[ -e $FIXDIR/MPASSIT/${fn}_analysis_mean ]]; then
                ln -sf $FIXDIR/MPASSIT/${fn}_analysis_mean $fn
            else
                mecho0 "${RED}ERROR${NC}: file ${BLUE}$FIXDIR/MPASSIT/${fn}_analysis_mean${NC} not exist."
                return
            fi
        fi
    done

    fn="histlist_soil"
    if [[ ! -e $fn ]]; then
        #if [[ $verb -eq 1 ]]; then echo "Linking $fn ..."; fi
        if [[ -e $FIXDIR/MPASSIT/${fn} ]]; then
            ln -sf $FIXDIR/MPASSIT/${fn} $fn
        else
            mecho0 "${RED}ERROR${NC}: file ${BLUE}$FIXDIR/MPASSIT/${fn}${NC} not exist."
            return
        fi
    fi

    #
    # prepare_mpassit
    fcst_lauch_time=$(date -u -d @${iseconds} +%H%M)
    fcst_time_str=$(date -u -d @$iseconds +%Y-%m-%d_%H.%M.%S)

    # shellcheck disable=SC2034
    prior_file="${dawrkdir}/jedi_solver/prior_mean.nc"
    # shellcheck disable=SC2034
    post_file="${dawrkdir}/jedi_solver/ana/mem000.nc"
    bkg_file="${dawrkdir}/jedi_solver/ens/mem001.nc"

    for stage in prior post; do
        #
        # Check MPASSIT status
        #
        if [[ -f done.mpassit${stage} ]]; then
            mecho0 "MPASSIT done for ${PURPLE}${stage}${NC}"
            continue
        fi

        if [[ -f running.mpassit${stage} || -f queue.mpassit${stage} ]]; then
            mecho0 "MPASSIT is running/queued for ${PURPLE}${stage}${NC}"
            continue
        fi

        if [[ -f error.mpassit${stage} ]]; then
            mecho0 "MPASSIT failed for ${PURPLE}${stage}${NC} "
            return
        fi

        file_ref="${stage}_file"
        org_file="${!file_ref}"
        filename="./${stage}_mean.nc"

        if [[ $dorun == true ]]; then
            while [[ ! -f ${org_file} ]]; do
                if [[ $verb -eq 1 ]]; then
                    mecho0 "Waiting for $org_file ..."
                fi
                sleep 10
            done
            {
                echo -e "\nCopying the stage file:\n"
                echo "cp ${org_file} ${filename}"
                cp ${org_file} ${filename}
            } &> merge_${stage}.log

            # Take background file, look for every variable except those listed in ${var_list},
            # and append them into the analysis file.
            mecho0 "Merging background datasets to ${CYAN}${filename}${NC} ..."
            {
                echo -e "\nRunning NCO to merge background static datasets to the stage file:\n"
                echo "${runcmd_str} ncks -A -C -x -v ${anlys_varstr} ${bkg_file} ${filename}"
                ${runcmd_str} ncks -A -C -x -v ${anlys_varstr} "${bkg_file}" "${filename}"
            } &>> merge_${stage}.log
        fi

        nmlfile="namelist.fcst_${stage}"
        cat << EOF > $nmlfile
&config
    grid_file_input_grid = "${rundir}/init/${domname}.invariant.nc"
    hist_file_input_grid = "${filename}"
    diag_file_input_grid = "${filename}"
    file_target_grid     = "${rundir}/${domname/*_/geo_}/geo_em.d01.nc"
    target_grid_type     = "file"
    output_file          = "MPASSIT_${stage}.${fcst_time_str}.nc"
    interp_diag          = .true.
    interp_hist          = .true.
    wrf_mod_vars         = .true.
    esmf_log             = .false.
/
EOF

        #
        # Create job script and submit it
        #
        jobscript="run_mpassit_${stage}.${mach}"

        declare -A jobParms=(
            [PARTION]="${partition_filter}"
            [NOPART]="${npepost}"
            [JOBNAME]="mpassit_${stage}"
            [CPUSPEC]="${claim_cpu_post}"
            [HHHSTR]="${stage}"
        )
        if [[ "${mach}" == "pbs" ]]; then
            jobParms[NNODES]="${nnodes_post}"
            # shellcheck disable=SC2034
            jobParms[NCORES]="${ncores_post}"
        fi

        submit_a_job "$wrkdir" "mpassit${stage}" "jobParms" "$TEMPDIR/run_mpassit.${mach}" "$jobscript" ""
    done
}

########################################################################

function run_mpassit {
    # $1        $2
    # wrkdir    iseconds
    local wrkdir=$1
    local iseconds=$2

    #
    # Build working directory
    #
    local wrkdir=$wrkdir/mpassit
    mkwrkdir $wrkdir 0
    cd $wrkdir || return

    #
    # Check MPASSIT status
    #
    if [[ -f done.mpassit ]]; then
        mecho0 "MPASSIT done for all forecast minutes"
        return
    fi

    if [[ -f running.mpassit || -f queue.mpassit ]]; then
        mecho0 "MPASSIT is running/queued for all forecast minutes"
        return
    fi

    if [[ -f error.mpassit ]]; then
        mecho0 "MPASSIT failed for all forecast minutes "
        return
    fi

    minstr=$(printf "%02d" $((intvl_sec/60)) )
    #minstr="00"
    fcst_minutes=()
    if [[ ${damode} == "init" || $icyc -eq 0 ]]; then
        fcst_minutes=("00")
    fi
    fcst_minutes+=("${minstr}")

    #
    # Prepare MPASSIT working files
    #
    if [[ ${#fcst_minutes[@]} -gt 0 ]]; then
        if [[ "${mpscheme}" == "mp_nssl2m" ]]; then
            fileappend="NSSL"
        else
            fileappend="THOM"
        fi

        jobarrays=()
        for mem in $(seq 1 $ENS_SIZE); do
            memstr=$(printf "%02d" $mem)
            memdir=$wrkdir/mem$memstr
            mkwrkdir $memdir 0
            cd $memdir || return

            rm -f core.*           # Maybe core-dumped, resubmission will solves the problem if the machine is unstable.

            # Linking working file for this member
            parmfiles=(diaglist histlist_2d histlist_3d histlist_soil)
            for fn in "${parmfiles[@]}"; do
                if [[ ! -e $fn ]]; then
                    #if [[ $verb -eq 1 ]]; then echo "Linking $fn ..."; fi
                    if [[ -e $FIXDIR/MPASSIT/${fn}.${fileappend} ]]; then
                        ln -sf $FIXDIR/MPASSIT/${fn}.${fileappend} $fn
                    elif [[ -e $FIXDIR/MPASSIT/${fn} ]]; then
                        ln -sf $FIXDIR/MPASSIT/$fn .
                    else
                        mecho0 "${RED}ERROR${NC}: file ${BLUE}$FIXDIR/MPASSIT/${fn}${NC} not exist."
                        return
                    fi
                fi
            done
            jobarrays+=("$mem")
        done

        jobarrays_str=$(get_jobarray_str "${mach}" "${jobarrays[@]}")

        cd $wrkdir || return

        run_mpassit_alltimes "${wrkdir}" "${iseconds}" "${fcst_minutes[*]}" "${jobarrays_str}"
    fi
}

########################################################################

function run_mpassit_alltimes {
    # $1        $2
    # wrkdir    iseconds
    local -r wrkdir=$1
    local -r iseconds=$2
    local fcsttimes
    local -r jobarraystr=$4

    IFS=" " read -r -a fcsttimes <<< "$3"

    cd $wrkdir || return

    # Loop over forecast minutes
    local minsec=3600
    local maxsec=0

    for minstr in "${fcsttimes[@]}"; do
        (( i=10#${minstr}*60 ))
        (( i > maxsec )) && maxsec=$i
        (( i < minsec )) && minsec=$i

        prepare_mpassit_onetime $wrkdir ${iseconds} $i 5
        local estatus=$?               # number of missing members
        if [[ ${estatus} -gt 0 ]]; then
            echo -e "${PURPLE}${estatus}${NC} files missing"
            exit 1
        fi
    done

    #
    # Create job script and submit it
    #
    cd $wrkdir || return

    jobscript="run_mpassit.${mach}"

    declare -A jobParms=(
        [PARTION]="${partition_filter}"
        [NOPART]="$npepost"
        [JOBNAME]="mpassit_${eventtime}"
        [CPUSPEC]="${claim_cpu_post}"
        [CLAIMTIME]="${claim_time_mpassit_alltimes}"
        [HHMINSTR]=""
        [FCST_START]="${minsec}"
        [FCST_END]="${maxsec}"
        [FCST_INTVL]="${intvl_sec}"
    )
    if [[ "${mach}" == "pbs" ]]; then
        jobParms[NNODES]="${nnodes_post}"
        # shellcheck disable=SC2034
        jobParms[NCORES]="${ncores_post}"
    fi

    submit_a_job "$wrkdir" "mpassit" "jobParms" "$TEMPDIR/run_mpassit_array.${mach}" "$jobscript" "$jobarraystr"
}

########################################################################

function prepare_mpassit_onetime {
    # Work for one forecast time and all ensemble members
    # 1. Wait for the history/diag files
    # 2. Create namelist files

    # $1        $2
    # wrkdir    iseconds
    local -r wrkdir=$1
    local -r iseconds=$2
    local -r fctseconds=$3
    local -r waitseconds=$4   # run all time together, it does not have to wait

    cd $wrkdir || return

    fminstr=$(printf "%03d" $((fctseconds/60)))
    fcst_lauch_time=$(date -u -d @${iseconds} +%H%M)

    isec=$(( iseconds+fctseconds ))
    fcst_time_str=$(date -u -d @$isec +%Y-%m-%d_%H.%M.%S)

    outdone=false
    jobarrays=()
    for mem in $(seq 1 $ENS_SIZE); do
        memstr=$(printf "%02d" $mem)
        memdir=$wrkdir/mem$memstr
        mkwrkdir $memdir 0
        cd $memdir || return

        rm -f core.*           # Maybe core-dumped, resubmission will solves the problem if the machine is unstable.

        fcstmemdir=$(upnlevels $memdir 2)
        histfile="$fcstmemdir/fcst_$memstr/${domname}_${memstr}.history.${fcst_time_str}.nc"
        diagfile="$fcstmemdir/fcst_$memstr/${domname}_${memstr}.diag.${fcst_time_str}.nc"

        if [[ $dorun == true ]]; then
            for fn in $histfile $diagfile; do
                if [[ $outdone == false ]]; then
                    mecho0 "Checking forecast files at $fminstr for all $ENS_SIZE memebers from dacycles${daffix}/${fcst_lauch_time} ..."
                    outdone=true
                fi
                while [[ ! -f $fn ]]; do
                    if [[ $verb -eq 1 ]]; then
                        mecho0 "Waiting for $fn ..."
                    fi
                    sleep 10
                done
                fileage=$(( $(date +%s) - $(stat -c %Y -- "$fn") ))
                if [[ $fileage -lt $waitseconds ]]; then
                    if [[ $verb -eq 1 ]]; then mecho0 "Waiting for $fn ..."; fi
                    sleep "$waitseconds"
                fi
            done
        fi

        nmlfile="namelist.fcst_$fminstr"
        cat << EOF > $nmlfile
&config
    grid_file_input_grid = "$rundir/init/${domname}_${memstr}.init.nc"
    hist_file_input_grid = "$histfile"
    diag_file_input_grid = "$diagfile"
    file_target_grid     = "$rundir/${domname/*_/geo_}/geo_em.d01.nc"
    target_grid_type     = "file"
    output_file          = "$memdir/MPASSIT_${memstr}.${fcst_time_str}.nc"
    interp_diag          = .true.
    interp_hist          = .true.
    wrf_mod_vars         = .true.
    esmf_log             = .false.
/
EOF
    done

    cd $wrkdir || return

    return 0
}


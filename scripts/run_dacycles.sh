                cwpobs_list+=("${cwpobs}")
            fi
        done
        # mecho0 "Using CWP observations ${WHITE}${cwpobs_list[*]}${NC}"
        # To join an array while ensuring you only add elements that don't already exist in the target (finding the union of the two sets)
        join_arrays obs_ids cwpobs_list

        return
    fi

    #-----------------------------------------------------------------------
    # Link/Copy observation files to working directory
    #-----------------------------------------------------------------------

    for (( j=0; j < 5; $((j=j+1)) )); do
        #for l in -1 1; do
        l=-1            # looking back only
            curr_sec=$(( iseconds + l*j*60))
            #curr_year=$(date -u -d @$curr_sec +%Y)
            curr_date=$(date -u -d @$curr_sec +%Y%m%d)
            curr_datetime=$(date -u -d @$curr_sec +%Y%m%d%H%M)

            cwpfile="${config_OBS_CWP_DIR}/${curr_date}/${curr_datetime}_GOES19_CWP_OBS.nc"

            if [[ ${verbose} == true ]]; then mecho0 "Looking for CWP data valid: ${DARK}${curr_datetime}${NC} as ${cwpfile}"; fi

            if [[ -s "${cwpfile}" ]]; then
                mecho0 "Using CWP file ${CYAN}${cwpfile}${NC}"
                #break 2
                break
            fi

        #    [[ $j -eq 0 ]] && break
        #done
    done

    if [[ ! -s ${cwpfile} ]]; then

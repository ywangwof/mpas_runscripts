function parse_args {

    declare -Ag args

    #-------------------------------------------------------------------
    # Parse command line arguments
    #-------------------------------------------------------------------

    while [[ $# -gt 0 ]]; do
        key="$1"

        case $key in
            -h)
                usage 0
                ;;
            -n)
                args["dorun"]=false
                ;;
            -v)
                args["verb"]=1
                ;;
            -r)
                args["rt_run"]=true
                ;;
            -k)
                if [[ $2 =~ [012] ]]; then
                    args["overwrite"]=$2
                    shift
                else
                    echo -e "${RED}ERROR${NC}: option for ${BLUE}-k${NC} can only be [${YELLOW}0-2${NC}], but got ${PURPLE}$2${NC}."
                    usage 1
                fi
                ;;
            -c | -a | -d )
                args["cleanoption"]="$key"
                if [[ "$2" == "filter" || "$2" == "mpas" ]]; then
                    args["cleanjobs"]+=" $2"
                    shift
                fi
                ;;
            -m)
                if [[ ${2^^} == "JET" ]]; then
                    args["machine"]=Jet
                elif [[ ${2^^} == "VECNA" ]]; then
                    args["machine"]=Vecna
                elif [[ ${2^^} == "HERCULES" ]]; then
                    args["machine"]=Hercules
                elif [[ ${2^^} == "CHEYENNE" || ${2^^} == "DERECHO" ]]; then
                    args["machine"]=Cheyenne
                else
                    echo -e "${RED}ERROR${NC}: Unsupported machine name, got ${PURPLE}$2${NC}."
                    usage 1
                fi
                shift
                ;;
            -f)
                args["config_file"]="$2"
                shift
                ;;
            -i)
                if [[ $2 =~ ^[0-9]{4}$ ]]; then
                    args["inittime"]=$2
                else
                    echo -e "${RED}ERROR${NC}: Initial time should be ${GREEN}HHMM${NC}, got ${PURPLE}$2${NC}."
                    usage 1
                fi
                shift
                ;;
            -s )
                if [[ $2 =~ ^[0-9]{4}$ || $2 =~ ^[0-9]{12}$ ]]; then
                    args["eventtime"]="${2}"
                else
                    echo -e "${RED}ERROR${NC}: Start time should be in ${GREEN}HHMM${NC} or ${GREEN}YYYYmmddHHMM${NC}, got ${PURPLE}$2${NC}."
                    usage 1
                fi
                shift
                ;;
            -e )
                if [[ $2 =~ ^[0-9]{4}$ || $2 =~ ^[0-9]{12}$ ]]; then
                    args["endtime"]=$2
                else
                    echo -e "${RED}ERROR${NC}: End time should be in ${GREEN}HHMM${NC} or ${GREEN}YYYYmmddHHMM${NC}, got ${PURPLE}$2${NC}."
                    usage 1
                fi
                shift
                ;;
            -*)
                echo -e "${RED}ERROR${NC}: Unknown option: ${PURPLE}$key${NC}"
                usage 2
                ;;
            ioda* | jedi_* | update_* | mpas* | clean* )
                args["jobs"]="${key//,/ }"
                ;;
            *)
                if [[ $key =~ ^[0-9]{8}$ ]]; then
                    args["eventdate"]="${key}"
                elif [[ -d $key ]]; then
                    args["WORKDIR"]="${key}"
                elif [[ -f $key ]]; then
                    args["config_file"]="${key}"
                else
                    echo  -e "${RED}ERROR${NC}: unknown argument, get ${PURPLE}$key${NC}."
                    usage 3
                fi
                ;;
        esac
        shift # past argument or value
    done
}

########################################################################

function run_ioda {
    # $1        $2
    # wrkdir    iseconds

    local wrkdir=$1               # DA directory for this cycle
    local iseconds=$2

    if [[ ! -d $wrkdir ]]; then
        mecho0 "run_ioda: Working directory $wrkdir not exist"
        exit 1
    fi

    anlys_date=$(date -u -d @$iseconds  +%Y%m%d%H)
    anlys_hour=$(date -u -d @$iseconds  +%H)
    anlys_min=$(date -u -d @$iseconds   +%M)

    #------------------------------------------------------
    # Run ioda_bufr for all bufr observation files
    #------------------------------------------------------

    if [[ ${anlys_min} == "00" && ${use_BUFR} == true ]]; then
        run_ioda_bufr ${wrkdir} ${iseconds}
    fi

    #------------------------------------------------------
    # Run ioda_mrms_refl for reflectivity
    #------------------------------------------------------
    if [[ ${use_REF} == true ]]; then
        run_ioda_mrms_refl ${wrkdir} ${iseconds}
    fi
}

########################################################################

function run_ioda_bufr {
    # $1        $2
    # wrkdir    iseconds

    local wrkdir=$1               # DA directory for this cycle
    local iseconds=$2

    #
    # Return if is running or is done
    #
    if [[ -f $wrkdir/ioda_bufr/running.ioda_bufr || -f $wrkdir/ioda_bufr/done.ioda_bufr || -f $wrkdir/ioda_bufr/queue.ioda_bufr ]]; then
        return
    fi

    #------------------------------------------------------
    # Run ioda_bufr for all bufr observation files
    #------------------------------------------------------

    mkwrkdir $wrkdir/ioda_bufr 1     # 0: Keep existing directory as is
                                     # 1: Remove existing same name directory
    cd $wrkdir/ioda_bufr || exit $?


    jobscript="run_ioda_bufr.${mach}"

    declare -A jobParms=(
        [PARTION]="${partition_filter}"
        [NOPART]="1"
        [JOBNAME]="ioda_bufr_${eventtime}"
        [CPUSPEC]="${claim_cpu_ioda}"
        [EXEDIR]="${EXEDIR}/jedi"
        [CPCMD]="${cpcmd}"
        [CURRDATE]="${anlys_date}"
        [CYCHR]="${anlys_hour}"
        [OBSDIR]="${OBS_DIR}/obs_rap"
        [FIXDIR]="${FIXDIR}"
        [ROOTDIR]="${rootdir}"
        [GRIDFILE]="${rundir}/$domname/${domname}.grid.nc"
        [RRFSDIR]="${rrfs_dir}"
        [MODULE]="${rrfs_modulename}"
    )
    if [[ "${mach}" == "pbs" ]]; then
        jobParms[NNODES]="1"
        jobParms[NCORES]="1"
    fi

    submit_a_job $wrkdir/ioda_bufr "ioda_bufr" jobParms $TEMPDIR/$jobscript $jobscript ""
}

########################################################################

function run_ioda_mrms_refl {
    # $1        $2
    # wrkdir    iseconds

    local wrkdir=$1               # DA directory for this cycle
    local iseconds=$2

    #
    # Return if is running or is done
    #
    if [[ -f $wrkdir/ioda_mrms_refl/running.ioda_mrms_refl || -f $wrkdir/ioda_mrms_refl/done.ioda_mrms_refl || -f $wrkdir/ioda_mrms_refl/queue.ioda_refl ]]; then
        return
    fi

    #------------------------------------------------------
    # Run ioda_mrms_refl for MRMS observation files
    #------------------------------------------------------

    mkwrkdir $wrkdir/ioda_mrms_refl 1     # 0: Keep existing directory as is
                                     # 1: Remove existing same name directory
    cd $wrkdir/ioda_mrms_refl || exit $?

    #
    #-----------------------------------------------------------------------
    #
    # link or copy background files
    #
    #-----------------------------------------------------------------------
    #
    gridfile="${rundir}/$domname/${domname}.grid.nc"

    mecho0 "meshgrid file is ${CYAN}${gridfile}${NC}"
    ln -sf "${gridfile}" grid.nc

    #
    #-----------------------------------------------------------------------
    #
    # link/copy observation files to working directory
    #
    #-----------------------------------------------------------------------
    #
    obs_appendix="grib2"
    OBSPATH_NSSLMOSIAC="${OBS_DIR}/reflectivity"
    #
    #-----------------------------------------------------------------------
    #
    # Link to the MRMS operational data
    #
    #-----------------------------------------------------------------------
    #
    if [ -f filelist_mrms ]; then rm -f filelist_mrms; fi

    for (( j=0; j < 5; $((j=j+1)) )); do
        for l in -1 1; do
            curr_sec=$(( iseconds + l*j*60))
            curr_time=$(date -u -d @$curr_sec +%Y%m%d-%H%M)
            mecho0 "Looking for data valid: ${PURPLE}${curr_time}${NC}"

            mapfile -t fileslist < <(compgen -G "${OBSPATH_NSSLMOSIAC}/MergedReflectivityQC_*_${curr_time}??.${obs_appendix}" | sort -V)
            if [ ${#fileslist[@]} -ge 10 ] && [ ! -e filelist_mrms ]; then
                mecho0 "Found ${YELLOW}${#fileslist[@]}${NC} GRIB-2 files from ${CYAN}${OBSPATH_NSSLMOSIAC}${NC}"
                for nsslfile in "${fileslist[@]}"; do
                    ${cpcmd}   "${nsslfile}" .
                    base_filename=$(basename "${nsslfile}")
                    echo "${base_filename}" >> filelist_mrms
                    mecho0 "Copying MRMS files ${CYAN}${base_filename}${NC} ...."
                done
                break 2
            fi

            [[ $j -eq 0 ]] && break
        done
    done
    #
    #
    if [ ! -s filelist_mrms ]; then rm -f filelist_mrms; fi

    if [ -s filelist_mrms ]; then
        if [ "${obs_appendix}" == "grib2.gz" ]; then
           gzip -d ./*.gz
           mv filelist_mrms filelist_mrms_org
           ls "MergedReflectivityQC_*_${curr_time}??.grib2" > filelist_mrms
        fi

        numgrib2=$(wc -l < filelist_mrms)
        mecho0 "Using radar data from: ${LIGHT_BLUE}$(head -n 1 filelist_mrms | xargs dirname)${NC}"
        mecho0 "NSSL grib2 file levels = ${YELLOW}$numgrib2${NC}"
    else
        mecho0 "${RED}ERROR${NC}: Not enough radar reflectivity files available for cycle ${anlys_date}${anlys_min}."
        exit 1
    fi

    #-----------------------------------------------------------------------
    #
    # Create namelist file
    #
    #-----------------------------------------------------------------------

    RADAR_REF_THINNING=1
    if [ ${RADAR_REF_THINNING} -eq 2 ]; then     # heavy data thinning, typically used for EnKF
        precipdbzhorizskip=1
        precipdbzvertskip=2
        clearairdbzhorizskip=2
        clearairdbzvertskip=4
    elif [ ${RADAR_REF_THINNING} -eq 1 ]; then   # light data thinning, typically used for hybrid EnVar
        precipdbzhorizskip=1
        precipdbzvertskip=1
        clearairdbzhorizskip=1
        clearairdbzvertskip=1
    else                                         # no data thinning
        precipdbzhorizskip=0
        precipdbzvertskip=0
        clearairdbzhorizskip=0
        clearairdbzvertskip=0
    fi

    cat << EOF > namelist.mosaic
&setup
    analysis_time = ${anlys_date}${anlys_min},
    dataPath = './',
/
&setup_netcdf
    output_netcdf            = .true.,
    max_height               = 11001.0,
    use_clear_air_type       = .true.,
    precip_dbz_thresh        = 10.0,
    clear_air_dbz_thresh     = 5.0,
    clear_air_dbz_value      = 0.0,
    precip_dbz_horiz_skip    = ${precipdbzhorizskip},
    precip_dbz_vert_skip     = ${precipdbzvertskip},
    clear_air_dbz_horiz_skip = ${clearairdbzhorizskip},
    clear_air_dbz_vert_skip  = ${clearairdbzvertskip},
    grid_spacing_deg         = 0.03
/
EOF

    #------------------------------------------------------
    # Run process_NSSL_mosaic.exe
    #------------------------------------------------------

    jobscript="run_ioda_mrms_refl.${mach}"

    declare -A jobParms=(
        [PARTION]="${partition_filter}"
        [NOPART]="${numgrib2}"
        [JOBNAME]="ioda_refl_${eventtime}"
        [CPUSPEC]="${claim_cpu_ioda_refl}"
        [EXEDIR]="${EXEDIR}/jedi"
        [CURRDATE]="${anlys_date}${anlys_min}"
        [ROOTDIR]="${rootdir}"
        [RRFSDIR]="${rrfs_dir}"
        [MODULE]="${rrfs_modulename}"
    )
    if [[ "${mach}" == "pbs" ]]; then
        jobParms[NNODES]="1"
        jobParms[NCORES]="1"
    fi

    submit_a_job $wrkdir/ioda_mrms_refl "ioda_refl" jobParms $TEMPDIR/$jobscript $jobscript ""
}


    # Run ioda_cwp for the found observation file
    #------------------------------------------------------

    mkwrkdir $wrkdir/ioda_cwp 1      # 0: Keep existing directory as is
                                     # 1: Remove existing same name directory
    cd $wrkdir/ioda_cwp || exit $?

    #-----------------------------------------------------------------------
    # Process the GOES CWP data file
    #
    # 0: CWP_ZERO - cwp; 1: LWP        2: IWP     3: CWP_ZERO_NIGHT
    # 4: LWP_NIGHT; 5: IWP_NIGHT
    #-----------------------------------------------------------------------

    (
    module purge
    module use ${rrfs_dir}/modulefiles
    module load rrfs/ursa.intel

    # pyioda libraries
    PYIODALIB=$(echo "${rrfs_dir}"/sorc/RDASApp/build/lib/python3.*)
    export PYTHONPATH=${PYIODALIB}:${PYTHONPATH}

    ${rootdir}/observations/GOESCWP2ioda.py -d ${anlys_eventtime} ${cwpfile}
    )

    local istatus=$?
    # shellcheck disable=SC2181
    if [ $istatus -eq 0 ]; then
        touch done.ioda_cwp
        for cwpobs in "${cwp_obs_initial[@]}"; do
            filename="ioda_${cwpobs}_obs.nc"
            if [[ -s ${wrkdir}/ioda_cwp/${filename} ]]; then
                cwpobs_list+=("${cwpobs}")
            fi
        done
        mecho0 "Using CWP observations ${WHITE}${cwpobs_list[*]}${NC}"
        # To join an array while ensuring you only add elements that don't already exist in the target (finding the union of the two sets)
        join_arrays obs_ids cwpobs_list
    else
        mecho0 "${RED}ERROR${NC}: ${BROWN}${rootdir}/observations/GOESCWP2ioda.py${NC} failed."
        touch error.ioda_cwp
        exit "${istatus}"
    fi
}


        if [[ $aline == "!"* ]]; then
            echo "${line}" >> "${outfile}"
        else
            read -ra fields <<< "${aline}"
            if [[ ${#fields[@]} -ne 9 ]]; then
                mecho1 "${YELLOW}WARNING${NC}: get_convinfo expected 9 fields in ${PURPLE}${line}${NC}"
            fi

            atype="${fields[0]}"
            if [[ ${fields[1]} -ne 0 ]]; then
                type=$(printf "%03d" ${fields[1]})
                atype="${atype}${type}"
            fi
            if [[ ${fields[2]} -ne 0 ]]; then
                type=$(printf "%03d" ${fields[2]})

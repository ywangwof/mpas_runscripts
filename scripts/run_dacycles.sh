            wait_for_conditions "${jdiagfile}"
        fi
    fi

    mem_map_str="( "
    for k in "${!mem_map[@]}"; do
        mem_map_str+="[$k]='${mem_map[$k]}' "
    done
    mem_map_str+=" )"


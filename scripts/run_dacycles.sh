function read_convinfo_initial {
    # Read convinfo to determine whether to use observations by default generally. (use or not)
    #
    # USE_xxx in the configuration file to determine whether the observation
    # will be processed for a specific run.                                        (spcific test)
    #
    # The workflow (jedi_preparation) will check whether the used observations
    # will be available dynamically for each cycle.                                (have or not)
    #

    local infile="$1"
    local -n obs_list=$2           # for prepbufr observations
    local -n cwp_list=$3           # for CWP observations
    local -n obs_category=$4       # for prepbufr observations

    declare -a cwp_local_initial=("cwp" "lwp" "iwp" "cwp_night" "lwp_night" "iwp_night")
    declare -r cwp_local_regex=$(IFS='|'; echo "${cwp_local_initial[*]}")

    #file_content=$(< "${config_FIXDIR}/jedi/convinfo") # read in all content
    while read -r line; do
        # remove leading and trailing whitespace from a string
        read -r aline <<< "${line}"

        found=false
        if [[ $aline == "!"* ]]; then
            :
            #echo "${line}" >> "${outfile}"
        else
            read -ra fields <<< "${aline}"
            if [[ ${#fields[@]} -ne 9 ]]; then
                mecho1 "${YELLOW}WARNING${NC}: read_convinfo_initial expected 9 fields in ${PURPLE}${line}${NC}"
            fi

            atype="${fields[0]}"
            itype="${fields[1]}"
            isub="${fields[2]}"
            iuse="${fields[3]}"
            icat="${fields[8]}"

            if [[ ${itype} -ne 0 ]]; then
                type=$(printf "%03d" ${fields[1]})
                atype="${atype}${type}"
            fi
            if [[ ${isub} -ne 0 ]]; then
                type=$(printf "%03d" ${fields[2]})
                atype="${atype}_${type}"
            fi

            if [[ ${iuse} -eq 1 ]]; then
                local re_cwp="[[:space:]](${cwp_local_regex})[[:space:]]"
                if [[ " ${atype} " =~ ${re_cwp} ]]; then
                    cwp_list+=("${atype}")
                else
                    obs_list+=("$atype")
                    if [[ ${itype} -ne 0 ]]; then
                        icategory="${icat%%,*}"
                        local icategory_lc="${icategory,,}"
                        if [[ ! " ${obs_category[*]} " == *" ${icategory_lc} "* ]]; then
                            obs_category+=("${icategory_lc}")
                        fi
                    fi
                fi
            fi
        fi
    done < "${infile}"

    #obs_id_string=$(join_by , "${obs_list[@]}")
    #obs_category_str=$(join_by , "${obs_category[@]}")
}


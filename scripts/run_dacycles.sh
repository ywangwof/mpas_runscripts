function run_ioda_mrms_refl {
    # $1        $2
    # wrkdir    iseconds

    local wrkdir=$1               # DA directory for this cycle
    local iseconds=$2

    #------------------------------------------------------
    # Run ioda_mrms_refl for MRMS observation files
    #------------------------------------------------------

    #
    # Return if is running or is done
    #
    if [[ -f $wrkdir/ioda_mrms_refl/running.ioda_mrms_refl   \
       || -f $wrkdir/ioda_mrms_refl/done.ioda_mrms_refl      \
       || -f $wrkdir/ioda_mrms_refl/queue.ioda_refl ]]; then
        # shellcheck disable=SC2034
        local ids_refl10cm=("refl10cm")
        join_arrays obs_ids ids_refl10cm
        return
    fi

    mkwrkdir $wrkdir/ioda_mrms_refl 1     # 0: Keep existing directory as is
                                     # 1: Remove existing same name directory
    cd $wrkdir/ioda_mrms_refl || exit $?

    anlys_date=$(date -u -d @$iseconds  +%Y%m%d)
    anlys_hour=$(date -u -d @$iseconds  +%H)
    anlys_min=$(date -u -d @$iseconds   +%M)

    #
    #-----------------------------------------------------------------------
    # link or copy background files
    #-----------------------------------------------------------------------
    #
    gridfile="${rundir}/$domname/${domname}.grid.nc"

    #mecho0 "meshgrid file is ${CYAN}${gridfile}${NC}"
    ${lncmd} "${gridfile}" grid.nc

    #-----------------------------------------------------------------------
    # Link the MRMS  data file
    #-----------------------------------------------------------------------
    #
    obs_appendix="grib2"

    if [ -f filelist_mrms ]; then rm -f filelist_mrms; fi

    mecho0n "Looking for reflectivity data valid:"
    for (( j=0; j < 5; $((j=j+1)) )); do
        for l in -1 1; do
            curr_sec=$(( iseconds + l*j*60))
            curr_time=$(date -u -d @$curr_sec +%Y%m%d-%H%M)
            curr_date=$(date -u -d @$curr_sec +%Y%m%d)

            mapfile -t fileslist < <(compgen -G "${config_OBS_REF_DIR}/${curr_date}/*MergedReflectivityQC_*_${curr_time}??.${obs_appendix}" | sort -V)
            if [ ${#fileslist[@]} -ge 10 ] && [ ! -e filelist_mrms ]; then
                echo -en " ${WHITE}${curr_time}${NC}\n"
                mecho0 "Found ${YELLOW}${#fileslist[@]}${NC} GRIB-2 files from ${CYAN}${config_OBS_REF_DIR}/${curr_date}${NC}"
                for nsslfile in "${fileslist[@]}"; do
                    ${cpcmd}   "${nsslfile}" .
                    base_filename=$(basename "${nsslfile}")
                    echo "${base_filename}" >> filelist_mrms
                    if [[ ${verbose} == true ]]; then mecho0 "Copying MRMS files ${CYAN}${base_filename}${NC} ...."; fi
                done
                break 2
            else
                echo -en " ${DARK}${curr_time}${NC},"
            fi

            [[ $j -eq 0 ]] && break
        done
    done
    #
    #
    if [ ! -s filelist_mrms ]; then rm -f filelist_mrms; fi

    if [ -s filelist_mrms ]; then
        if [ "${obs_appendix}" == "grib2.gz" ]; then
           gzip -d ./*.gz
           mv filelist_mrms filelist_mrms_org
           ls "MergedReflectivityQC_*_${curr_time}??.grib2" > filelist_mrms
        fi

        numgrib2=$(wc -l < filelist_mrms)
        #mecho0 "Using radar data from: ${LIGHT_BLUE}$(head -n 1 filelist_mrms | xargs dirname)${NC}"
        #mecho0 "NSSL grib2 file levels = ${YELLOW}$numgrib2${NC}"

        obs_ids+=("refl10cm")
    else
        echo ""
        mecho0 "${YELLOW}INFO${NC}: Not enough radar reflectivity files from ${LIGHT_BLUE}${config_OBS_REF_DIR}/${anlys_date}${NC} available for cycle ${anlys_date}${anlys_hour}${anlys_min}."
        return   #exit 1
    fi

    #-----------------------------------------------------------------------
    # Create namelist file
    #-----------------------------------------------------------------------

    RADAR_REF_THINNING=1
    if [ ${RADAR_REF_THINNING} -eq 2 ]; then     # heavy data thinning, typically used for EnKF
        precipdbzhorizskip=1
        precipdbzvertskip=2
        clearairdbzhorizskip=2
        clearairdbzvertskip=4
    elif [ ${RADAR_REF_THINNING} -eq 1 ]; then   # light data thinning, typically used for hybrid EnVar
        precipdbzhorizskip=1
        precipdbzvertskip=1
        clearairdbzhorizskip=1
        clearairdbzvertskip=1
    else                                         # no data thinning
        precipdbzhorizskip=0
        precipdbzvertskip=0
        clearairdbzhorizskip=0
        clearairdbzvertskip=0
    fi

    cat << EOF > namelist.mosaic
&setup
    analysis_time = ${anlys_date}${anlys_hour}${anlys_min},
    dataPath = './',
/
&setup_netcdf
    output_netcdf            = .true.,
    max_height               = 11001.0,
    use_clear_air_type       = .true.,
    precip_dbz_thresh        = 10.0,
    clear_air_dbz_thresh     = 5.0,
    clear_air_dbz_value      = 0.0,
    precip_dbz_horiz_skip    = ${precipdbzhorizskip},
    precip_dbz_vert_skip     = ${precipdbzvertskip},
    clear_air_dbz_horiz_skip = ${clearairdbzhorizskip},
    clear_air_dbz_vert_skip  = ${clearairdbzvertskip},
    grid_spacing_deg         = 0.03
/
EOF

    #------------------------------------------------------
    # Run process_NSSL_mosaic.exe
    #------------------------------------------------------

    jobscript="run_ioda_mrms_refl.${mach}"

    nopart=13
    if [[ ${numgrib2} -gt ${nopart} ]]; then
        nopart=${numgrib2}
    fi

    declare -A jobParms=(
        [PARTION]="${config_partition_filter}"
        [NOPART]="${nopart}"
        [JOBNAME]="ioda_refl_${eventtime}"
        [CPUSPEC]="${config_claim_cpu_ioda_refl}"
        [EXEDIR]="${config_EXEDIR}/jedi"
        [CURRDATE]="${anlys_date}${anlys_hour}${anlys_min}"
        [ROOTDIR]="${rootdir}"
        [RRFSDIR]="${rrfs_dir}"
        [MODULE]="${rrfs_modulename}"
    )
    if [[ "${mach}" == "pbs" ]]; then
        jobParms[NNODES]="1"
        jobParms[NCORES]="1"
    fi

    submit_a_job $wrkdir/ioda_mrms_refl "ioda_refl" jobParms ${config_TEMPDIR}/$jobscript $jobscript ""
}


function run_mpassit_alltimes {
    # $1        $2
    # wrkdir    iseconds
    local -r wrkdir=$1
    local -r iseconds=$2
    local fcsttimes
    local -r jobarraystr=$4

    IFS=" " read -r -a fcsttimes <<< "$3"

    cd $wrkdir || return

    # Loop over forecast minutes
    local minsec=3600
    local maxsec=0

    for minstr in "${fcsttimes[@]}"; do
        (( i=10#${minstr}*60 ))
        (( i > maxsec )) && maxsec=$i
        (( i < minsec )) && minsec=$i

        prepare_mpassit_onetime $wrkdir ${iseconds} $i 5
        local estatus=$?               # number of missing members
        if [[ ${estatus} -gt 0 ]]; then
            echo -e "${PURPLE}${estatus}${NC} files missing"
            exit 1
        fi
    done

    #
    # Create job script and submit it
    #
    cd $wrkdir || return

    jobscript="run_mpassit.${mach}"

    declare -A jobParms=(
        [PARTION]="${config_partition_filter}"
        [NOPART]="${config_npepost}"
        [JOBNAME]="mpassit_${eventtime}"
        [CPUSPEC]="${config_claim_cpu_post}"
        [CLAIMTIME]="${config_claim_time_mpassit_alltimes}"
        [HHMINSTR]=""
        [FCST_START]="${minsec}"
        [FCST_END]="${maxsec}"
        [FCST_INTVL]="${config_intvl_sec}"
    )
    if [[ "${mach}" == "pbs" ]]; then
        jobParms[NNODES]="${config_nnodes_post}"
        # shellcheck disable=SC2034
        jobParms[NCORES]="${config_ncores_post}"
    fi

    submit_a_job "$wrkdir" "mpassit" "jobParms" "${config_TEMPDIR}/run_mpassit_array.${mach}" "$jobscript" "$jobarraystr"
}

